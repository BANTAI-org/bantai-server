-- Stores Firebase Cloud Messaging (FCM) tokens for system-level push notifications.
-- 
-- 1. A single user can have multiple devices (e.g., an old phone, a new phone, a tablet).
--    Therefore, this is a 1:N relationship from user_account.
-- 2. Tokens must be unique. If a user logs out and logs in on the same device, 
--    we update the last_updated_at rather than creating duplicates.
-- 3. If a user account is deleted, the ON DELETE CASCADE ensures all their 
--    device tokens are wiped.

CREATE TABLE IF NOT EXISTS user_device_token (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES user_account(id) ON DELETE CASCADE,
    
    -- The unique token generated by Firebase in the Flutter app
    fcm_token VARCHAR(255) NOT NULL UNIQUE,
    
    -- 'android', 'ios', or 'web'
    device_type VARCHAR(20) NOT NULL,
    
    last_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chck_device_type CHECK (device_type IN ('android', 'ios', 'web'))
);

-- Fast lookup when we need to send a notification to a specific user
CREATE INDEX idx_user_device_token_user_id ON user_device_token(user_id);

-- Helps with background cleanup tasks (e.g., deleting tokens older than 6 months)
CREATE INDEX idx_user_device_token_updated_at ON user_device_token(last_updated_at);


